"""Turn saved results into (1) failures.md per run and (2) a before/after table.

  python eval/report.py failures baseline
  python eval/report.py table baseline hybrid hybrid_rerank hybrid_rerank_rewrite [--readme]

Numbers are read from eval/results/<run>/summary.json. Nothing is typed in by hand.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from docuquery.evaluation import classify_failure  # noqa: E402

RESULTS = ROOT / "eval" / "results"


def pct(m: dict) -> str:
    return "n/a" if m["rate"] is None else f"{m['rate']*100:.1f}% ({m['num']}/{m['den']})"


def failures(run: str):
    rows = [json.loads(l) for l in (RESULTS / run / "raw.jsonl").read_text().splitlines() if l.strip()]
    lines = [f"# Failure cases: {run}\n",
             "Label = deterministic category. 'Why' is for YOU to fill in after reading the retrieved text.\n"]
    counts = {}
    for r in rows:
        label = classify_failure(r)
        if not label:
            continue
        counts[label] = counts.get(label, 0) + 1
        lines += [f"## {r['id']}: {label}", f"**Q:** {r['question']}  ",
                  f"**Gold:** {r.get('gold_answer')} ({r.get('gold_file')}, pages {r.get('gold_pages')})  "
                  if r.get("type") != "unanswerable" else "**Gold:** documents cannot answer this  ",
                  f"**Got:** {r.get('answer')}  ",
                  f"**Retrieved (file, page):** {[(x['file'], x['page']) for x in r.get('retrieved', [])]}  ",
                  f"**Note:** {r.get('note') or r.get('error') or ''}  ", "**Why (fill in):** \n"]
    lines.insert(2, "Counts: " + (", ".join(f"{k}={v}" for k, v in sorted(counts.items())) or "no failures") + "\n")
    path = RESULTS / run / "failures.md"
    path.write_text("\n".join(lines))
    print(f"Wrote {path}  ({sum(counts.values())} failing rows)")


def table(runs: list[str], readme: bool):
    summaries = [json.loads((RESULTS / r / "summary.json").read_text()) for r in runs]
    header = ["Run", "N (ans/unans)", "hit@1", "hit@3", "hit@5", "Correct (answerable)",
              "Abstains correctly (unanswerable)", "Faithfulness", "Overall correct"]
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for s in summaries:
        m = s["metrics"]
        out.append("| " + " | ".join([
            s["run_name"], f"{m['n_answerable']}/{m['n_unanswerable']}",
            pct(m["retrieval_hit"]["@1"]), pct(m["retrieval_hit"]["@3"]), pct(m["retrieval_hit"]["@5"]),
            pct(m["correct_answerable"]), pct(m["correct_abstention_on_unanswerable"]),
            pct(m["faithfulness_of_given_answers"]), pct(m["overall_correct"])]) + " |")
    text = "\n".join(out)
    (RESULTS / "RESULTS.md").write_text(
        "# Results (generated by eval/report.py from summary.json files)\n\n" + text + "\n")
    print(text)
    if readme:
        path = ROOT / "README.md"
        body = path.read_text()
        a, b = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
        path.write_text(body.split(a)[0] + a + "\n" + text + "\n" + b + body.split(b)[1])
        print("README.md results block updated.")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd == "failures":
        failures(args[0])
    elif cmd == "table":
        table([a for a in args if not a.startswith("--")], "--readme" in args)
    else:
        sys.exit(__doc__)
